import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parse } from "@babel/parser";
import traverse from "@babel/traverse";
import { parseSource, pluginsFor } from "../analyzer/parser.js";
import { UserError } from "../errors.js";
import type { SupportedExtension } from "../types/index.js";
import { unifiedDiff } from "./diff.js";
import type { ValidatedSuite } from "./validate.js";

export const GENERATED_HEADER = "// Generated by Assertloom.";

export class TestFileExistsError extends UserError {}

/** `src/math.ts` → `src/math.test.preview.ts`. Jest's default pattern ignores it until it has been run. */
export function previewPathFor(sourcePath: string): string {
  const ext = path.extname(sourcePath);
  return path.join(path.dirname(sourcePath), `${path.basename(sourcePath, ext)}.test.preview${ext}`);
}

/** `src/math.ts` → `src/math.test.ts`. */
export function testPathFor(sourcePath: string): string {
  const ext = path.extname(sourcePath);
  return path.join(path.dirname(sourcePath), `${path.basename(sourcePath, ext)}.test${ext}`);
}

/** Offsets inside template literals, where added indentation would change the string's value. */
function templateRanges(body: string, extension: SupportedExtension): Array<[number, number]> {
  const prefix = "async function __assertloomCase() {\n";
  const ranges: Array<[number, number]> = [];
  try {
    const ast = parse(`${prefix}${body}\n}`, { sourceType: "module", plugins: pluginsFor(extension) });
    traverse(ast, {
      TemplateLiteral({ node }) {
        if (node.start != null && node.end != null) ranges.push([node.start - prefix.length, node.end - prefix.length]);
      },
    });
  } catch {
    // Unparseable bodies are rejected later by parseSource; indent them naively.
  }
  return ranges;
}

function indent(text: string, spaces: number, extension: SupportedExtension): string {
  const pad = " ".repeat(spaces);
  const ranges = templateRanges(text, extension);
  let offset = 0;
  return text
    .split("\n")
    .map((line) => {
      const start = offset;
      offset += line.length + 1;
      if (ranges.some(([from, to]) => start > from && start < to)) return line;
      const trimmed = line.replace(/\r$/, "");
      return trimmed.trim() ? pad + trimmed : "";
    })
    .join("\n");
}

export function renderTestFile(options: {
  sourceFile: string;
  /** Mocks, imports, and setup that precede the describe blocks. */
  preamble: string[];
  suites: ValidatedSuite[];
  extension: SupportedExtension;
}): string {
  const blocks = options.suites.map(({ binding, cases }) => {
    const tests = cases.map((c) => {
      const comment = c.skipReason ? `  // Assertloom skipped this test: ${c.skipReason.replace(/\s+/g, " ")}\n` : "";
      const it = c.skipReason ? "it.skip" : "it";
      return `${comment}  ${it}(${JSON.stringify(c.name)}, ${c.async ? "async " : ""}() => {\n${indent(c.body, 4, options.extension)}\n  });`;
    });
    return `describe(${JSON.stringify(binding.binding)}, () => {\n${tests.join("\n\n")}\n});`;
  });

  const content = [
    `${GENERATED_HEADER} Source: ${options.sourceFile}. Review before committing.`,
    ...options.preamble,
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");

  parseSource(content, options.extension);
  return content;
}

export async function writeTestFile(
  filePath: string,
  content: string,
  force = false,
  /** Called with the changes before an existing file with different content is overwritten. */
  onOverwrite?: (diff: string[]) => void,
): Promise<{ overwritten: boolean }> {
  let existing: string | undefined;
  try {
    existing = await readFile(filePath, "utf8");
  } catch {
    // File does not exist yet.
  }

  if (existing !== undefined && !existing.startsWith(GENERATED_HEADER) && !force) {
    throw new TestFileExistsError(`${filePath} already exists and was not generated by Assertloom. Use --force to overwrite it.`);
  }
  if (existing !== undefined && existing !== content) onOverwrite?.(unifiedDiff(existing, content));

  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, content, "utf8");
  return { overwritten: existing !== undefined };
}
