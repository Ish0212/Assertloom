const DELETED = ["src/legacy.js", "src/slug.js"];

function git(cwd, ...args) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function write(root, files) {
  for (const [file, content] of Object.entries(files)) {
    const target = path.join(root, file);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}

/** Builds the repository in `root` and returns the base and head commit SHAs. */
export function makeConsumer(root) {
  mkdirSync(root, { recursive: true });
  git(root, "init", "--quiet", "--initial-branch=main");
  git(root, "config", "user.name", "Assertloom Fixture");
  git(root, "config", "user.email", "fixture@example.invalid");
  git(root, "config", "commit.gpgsign", "false");
  git(root, "config", "core.autocrlf", "false");
  write(root, BASE);
  git(root, "add", "--all");
  git(root, "commit", "--quiet", "-m", "base");
  const base = git(root, "rev-parse", "HEAD");

  git(root, "checkout", "--quiet", "-b", "feature");
  for (const file of DELETED) rmSync(path.join(root, file));
  write(root, HEAD);
  git(root, "add", "--all");
  git(root, "commit", "--quiet", "-m", "pull request change");
  const head = git(root, "rev-parse", "HEAD");
  return { base, head };
}

